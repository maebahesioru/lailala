// Prisma の `contains` は内部的に SQL の `LIKE`/`ILIKE` へ素の文字列を埋め込むため、
// ユーザー入力に含まれる `%` `_` `\` がそのままパターンのメタ文字として解釈される。
//
// 実害（2026-10-29 本番実測）:
//   /api/search/comments/?q=a%5C  → 6.0〜18.5 秒（通常 0.03 秒）
//   `ILIKE '%a\%'` の末尾 `\` が閉じ `%` をエスケープしてしまい、pg_trgm の
//   インデックスが使えず全件走査＋バックトラックになる。誰でも 1 リクエストで
//   ワーカーを十数秒占有できる＝簡易 DoS だった。
//
// PostgreSQL の LIKE の既定エスケープ文字は `\` なので、`\` 自体を最初に
// エスケープしてから `%` `_` をエスケープする（順序を逆にすると二重変換になる）。
export function escapeLike(value: string): string {
  return value.replace(/[\\%_]/g, (ch) => `\\${ch}`);
}
